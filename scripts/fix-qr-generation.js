const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');

// 1. UPDATE script-card.original.js
const scriptCardPath = path.join(rootDir, 'script-card.original.js');
let scriptCard = fs.readFileSync(scriptCardPath, 'utf8');

const targetCardChunk = `    async generateCardLinkQr() {
        const button = DOMElements.buttons.generateAutoQr;
        UIManager.setButtonLoadingState(button, true, 'جاري الحفظ...');
        try {
            await Utils.loadScript(Config.SCRIPT_URLS.qrCodeStyling);
            const designId = await ShareManager.saveDesign();
            if (!designId) {
                alert('فشل حفظ التصميم اللازم لإنشاء الرابط.');
                return;
            }

            UIManager.setButtonLoadingState(button, true, 'جاري الإنشاء...');
            const viewerUrl = new URL('viewer.html', window.location.href);
            viewerUrl.searchParams.set('id', designId);
            const finalUrl = viewerUrl.href;

            this.autoGeneratedQrDataUrl = await this.exportStyledQr(finalUrl);
            this.updateQrCodeDisplay();
            UIManager.announce("تم إنشاء QR Code بنجاح.");

        } catch (error) {
            console.error("Error generating shareable QR code:", error);
            let msg = "حدث خطأ. لم نتمكن من إنشاء رابط QR Code.";
            if (document.documentElement.lang === 'en') {
                msg = "An error occurred. We could not generate the QR Code link.";
            }
            if (error && error.message && error.message.trim() !== "") {
                msg += "\\n\\nError: " + error.message;
            }
            alert(msg);
        } finally {
            UIManager.setButtonLoadingState(button, false);
        }
    },`;

const replacementCardChunk = `    async generateCardLinkQr() {
        const button = DOMElements.buttons.generateAutoQr;
        if (button) UIManager.setButtonLoadingState(button, true, 'جاري الإنشاء...');
        try {
            await Utils.loadScript(Config.SCRIPT_URLS.qrCodeStyling);

            const isLoggedIn = (typeof Auth !== 'undefined' && Auth.isLoggedIn()) || !!localStorage.getItem('authUser');
            let designId = Config.currentDesignId || localStorage.getItem('nfc:editingDesignId');

            if (!designId && isLoggedIn) {
                if (button) UIManager.setButtonLoadingState(button, true, 'جاري الحفظ...');
                try {
                    designId = await ShareManager.saveDesign();
                } catch (e) {
                    console.warn('[QR] saveDesign error:', e);
                }
            }

            let finalUrl = '';
            if (designId) {
                const isEn = document.documentElement.lang === 'en' || window.location.pathname.includes('-en');
                const viewerPage = isEn ? 'viewer-en.html' : 'viewer.html';
                const viewerUrl = new URL(viewerPage, window.location.href);
                viewerUrl.searchParams.set('id', designId);
                finalUrl = viewerUrl.href;
            } else {
                finalUrl = ExportManager.getVCardString();
            }

            this.autoGeneratedQrDataUrl = await this.exportStyledQr(finalUrl);
            this.updateQrCodeDisplay();
            
            const isEn = document.documentElement.lang === 'en' || window.location.pathname.includes('-en');
            if (designId) {
                UIManager.announce(isEn ? "QR Code for card link generated successfully!" : "تم إنشاء QR Code لرابط البطاقة بنجاح.");
            } else {
                UIManager.announce(isEn ? "Contact QR Code generated!" : "تم إنشاء رمز QR لبيانات الاتصال بنجاح!");
            }

        } catch (error) {
            console.error("Error generating shareable QR code:", error);
            try {
                const vCardData = ExportManager.getVCardString();
                this.autoGeneratedQrDataUrl = await this.exportStyledQr(vCardData);
                this.updateQrCodeDisplay();
                const isEn = document.documentElement.lang === 'en' || window.location.pathname.includes('-en');
                UIManager.announce(isEn ? "Contact QR Code generated!" : "تم إنشاء رمز QR لبيانات الاتصال بنجاح!");
                return;
            } catch (fallbackErr) {
                console.warn('[QR] fallback also failed:', fallbackErr);
            }

            let msg = "حدث خطأ أثناء إنشاء QR Code. يرجى المحاولة مرة أخرى.";
            if (document.documentElement.lang === 'en') {
                msg = "An error occurred while generating QR Code. Please try again.";
            }
            alert(msg);
        } finally {
            if (button) UIManager.setButtonLoadingState(button, false);
        }
    },`;

if (scriptCard.includes(targetCardChunk)) {
    scriptCard = scriptCard.replace(targetCardChunk, replacementCardChunk);
    fs.writeFileSync(scriptCardPath, scriptCard, 'utf8');
    console.log('Updated script-card.original.js with robust QR code generation.');
} else {
    console.warn('Target chunk in script-card.original.js not found, applying regex replace.');
    scriptCard = scriptCard.replace(/async generateCardLinkQr\(\)[\s\S]*?finally\s*\{[\s\S]*?\}\s*\},/, replacementCardChunk);
    fs.writeFileSync(scriptCardPath, scriptCard, 'utf8');
    console.log('Regex updated script-card.original.js.');
}

